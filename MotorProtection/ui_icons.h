#pragma once

#include <stdint.h>

// 8x8 XBM icons (row-major, LSB = leftmost pixel) for the local SH1106 panel.
// Only the four MotorStatus states get dedicated icons; a FaultType is always
// shown as the warning-triangle icon plus a short text abbreviation.
// RUNNING / FAULT / COOLING have 3 frames cycled every ~450 ms. STOPPED is
// idle and stays on a single frame.

static const uint8_t ICON_STOPPED[8] = {
  0xFF, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xFF
};

static const uint8_t ICON_RUNNING_F[3][8] = {
  {0x01, 0x03, 0x07, 0x0F, 0x1F, 0x0F, 0x07, 0x03},
  {0x02, 0x06, 0x0E, 0x1E, 0x3E, 0x1E, 0x0E, 0x06},
  {0x04, 0x0C, 0x1C, 0x3C, 0x7C, 0x3C, 0x1C, 0x0C}
};

static const uint8_t ICON_FAULT_F[3][8] = {
  {0x08, 0x08, 0x1C, 0x1C, 0x3E, 0x3E, 0x7F, 0x00},
  {0x00, 0x08, 0x08, 0x1C, 0x1C, 0x3E, 0x3E, 0x7F},
  {0x08, 0x1C, 0x1C, 0x3E, 0x3E, 0x7F, 0x00, 0x00}
};

static const uint8_t ICON_COOLING_F[3][8] = {
  {0x08, 0x2A, 0x1C, 0x7F, 0x7F, 0x1C, 0x2A, 0x08},
  {0x00, 0x08, 0x2A, 0x1C, 0x7F, 0x1C, 0x2A, 0x08},
  {0x08, 0x2A, 0x1C, 0x7F, 0x1C, 0x2A, 0x08, 0x00}
};

#define ICON_RUNNING ICON_RUNNING_F[0]
#define ICON_FAULT   ICON_FAULT_F[0]
#define ICON_COOLING ICON_COOLING_F[0]

static const uint8_t ICON_AP[8] = {
  0x00, 0x3C, 0x42, 0x99, 0x81, 0x3C, 0x00, 0x18
};
